-- 关闭一条风险要留下**怎么关的**，不能只是打个勾。
--
-- 原来 risks 只有一个 resolved 布尔。它把「这条风险不用管了」和
-- 「我们做了什么让它不用管」压成了同一个比特，结果是复盘时最值得留下的
-- 那部分信息 —— 处置手段 —— 从来没被记下来过：
--
--   · 「等料风险关了」到底是换了供应商，还是改了工序绕过去，还是干脆
--     接受延期？三种处置的经验价值完全不同，下次遇到同类风险要抄的正是它
--   · 关闭时间也不能靠 updated_at 猜。改一次措辞就会刷新 updated_at，
--     而「什么时候不再是风险的」是个会被写进汇报的事实
--
-- 两列都允许为 NULL：历史数据里已经关掉的风险确实没有这两项，
-- 硬填一个默认值等于伪造记录。前端据此显示「（早期记录，未留处置说明）」。

ALTER TABLE risks ADD COLUMN resolved_at INTEGER;
ALTER TABLE risks ADD COLUMN resolution  TEXT;

-- 实施逾期自动顺延：改成**每个任务自己**的开关，去掉全局开关。
--
-- 一开始做成了设置里的一个全局开关。那是错的：一条活逾期了要不要自动把
-- 计划结束日往后推，是**这条活自己的排期决定**，不是全项目的统一偏好 ——
-- 同一个项目里，「关键路径上的活，逾期就该暴露出来」和
-- 「辅助性的活，计划跟着实际走就行」完全可能同时成立。
-- 全局开关逼用户二选一，只会让人在两个都不对的选项里挑一个。
--
-- 放在任务行上还买到两件事：
--   · 自动走现有的命令栈 —— 勾选/取消都能 ⌘Z，和改进度、改紧急度一样
--   · 自动随 save_project 的整项目 upsert 落库，零新机制
--
-- 默认 0：既有项目原样不动。一个新增字段的默认值去改写用户的排期是不可接受的，
-- 和 blocked.open 的默认值是同一条规矩。
--
-- 注意它是个**叶子任务**的开关：父任务的日期由子任务汇总（DESIGN.md §1.3），
-- 推它下一轮汇总就覆盖回去了。跨天逻辑只认叶子，父任务上这一列存了也忽略。

ALTER TABLE tasks ADD COLUMN auto_rollover INTEGER NOT NULL DEFAULT 0
  CHECK (auto_rollover IN (0, 1));

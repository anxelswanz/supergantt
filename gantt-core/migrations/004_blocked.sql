-- 受阻时段：任务区间内「这几天没能正常推进」的记录。
--
-- 存成任务行上的一个 JSON 字段，而不是独立的表。
--
-- 理由是撤销：它由「⌥ 在甘特条上拖」这个手势创建，而条子上其他所有拖拽
-- （移动 / 改工期 / 调进度）都能 ⌘Z，唯独这一个不能会很反直觉。
-- 放在任务行上，它就自动走现有的命令栈和 save_project 的整项目 upsert，
-- 一行新机制都不用加。
--
-- 代价是没法用 SQL 直接跨项目统计受阻天数 —— v3 真要做那个报表时，
-- 再把它抽成独立表并迁移，那时的需求也会更清楚。
--
-- 内容形如：
--   [{"id":"b1a2","from":"2026-08-15","to":"2026-08-17","reason":"equipment"}]
-- 日期用 ISO 串，和 start_date / end_date 同一套口径。

ALTER TABLE tasks ADD COLUMN blocked TEXT NOT NULL DEFAULT '[]';

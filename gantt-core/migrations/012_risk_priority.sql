-- 风险加一个「先做哪个」的刻度。
--
-- 和既有的 level（高/中/低）是**两个轴**，不是重复：
--   · level    = 多严重 —— 它真的发生的话有多糟
--   · priority = 先做哪个 —— 今天先盯哪一条
-- 一条「中等严重但这周就会揭晓」的风险该排在「很严重但三个月后才相关」的
-- 前面，单靠 level 表达不了。系统里因此有三套刻度（任务 P0–P3、
-- 事项 P0–P3、风险 level），这是已经权衡过并决定保留的（设计稿 §7）。
--
-- 它存在的直接原因是分拣：一条 P0 的事项晋升成风险时，优先级必须跟过去，
-- 否则「分拣完优先级就丢了」—— 用户刚刚做的那个判断在下一步被扔掉。
--
-- **可空**，而且没有默认值。历史数据没有优先级就是没有，界面显示一个空的
-- 优先级槽，不伪造一个「中」。新增字段的默认值去改写既有记录是不可接受的，
-- 和 blocked.open、tasks.auto_rollover 是同一条规矩。

ALTER TABLE risks ADD COLUMN priority INTEGER
  CHECK (priority IS NULL OR priority BETWEEN 0 AND 3);
